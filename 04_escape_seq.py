# Escape Sequence	            Description
# \n	                          New line
# \t	                         Horizontal tab
# \\	                         Backslash (\)
# \'	                         Single quote
# \"	                         Double quote
# \r	                         Carriage return
# \b	                         Backspace
# \f	                         Form feed
# \v	                         Vertical tab

#Example:
print("Hello\nWorld")                
print("Python\tProgramming")
print("C:\\Users\\Admin")
print('It\'s Python')
print("He said, \"Hello\"")
print("12345\rABC")
print("Helloo\b")
print("Hello\fWorld")
print("Hello\vWorld")

